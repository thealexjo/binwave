package migrationsim

import (
	"context"
	"database/sql"
	"fmt"
	"regexp"
	"strings"
	"sync"
	"time"
)

// Statement is one statement the simulation ran. DDL says that it reaches the binlog as a
// statement; the others (the copy, the triggers' work, the catch-up) reach it as row events.
type Statement struct {
	SQL string
	DDL bool
}

// Hooks let a test act between the phases of a migration. All are optional.
type Hooks struct {
	// AfterCreate runs when the shadow table has its new structure and nothing is copied yet.
	AfterCreate func()
	// DuringCopy runs after every copied chunk, counted from 1.
	DuringCopy func(chunk int)
	// BeforeCutover runs when the copy is done, before the tables are swapped.
	BeforeCutover func()
	// AfterCutover runs when the tables are swapped, before the clean-up.
	AfterCutover func()
}

// Options are what both tools share.
type Options struct {
	Hooks
	// ChunkSize is how many key values one chunk of the copy covers; 100 by default.
	ChunkSize int
	// ChunkPause waits between chunks, to make the copy last.
	ChunkPause time.Duration
	// KeepOld leaves the old table in place after the swap (pt-online-schema-change
	// --no-drop-old-table; gh-ost without --ok-to-drop-table).
	KeepOld bool
}

// PtOSCOptions are the options of pt-online-schema-change that change what it writes.
type PtOSCOptions struct {
	Options
	// DropSwap is --alter-foreign-keys-method=drop_swap: the original table is dropped and the
	// new one renamed, in two statements, instead of the atomic swap.
	DropSwap bool
}

// GhostOptions are the options of gh-ost that change what it writes.
type GhostOptions struct {
	Options
	// TwoStep is --cut-over=two-step: two ALTER TABLE ... RENAME statements, the table missing
	// between them, instead of the atomic RENAME TABLE.
	TwoStep bool
	// NoInitialDrops leaves out the DROP TABLE IF EXISTS of the leftovers of an earlier run,
	// which gh-ost writes with --initially-drop-ghost-table and --initially-drop-old-table.
	NoInitialDrops bool
}

// Runner runs simulated migrations of one table.
type Runner struct {
	db     *sql.DB
	schema string
	table  string

	mu  sync.Mutex
	log []Statement
}

// New returns a Runner for schema.table. db must connect with the privileges of an
// administrator: the tools create triggers and tables.
func New(db *sql.DB, schema, table string) *Runner {
	return &Runner{db: db, schema: schema, table: table}
}

// Statements returns what was run so far.
func (r *Runner) Statements() []Statement {
	r.mu.Lock()
	defer r.mu.Unlock()
	return append([]Statement(nil), r.log...)
}

// DDL returns the statements that reach the binlog as statements, normalized (see Normalize).
func (r *Runner) DDL() []string {
	var out []string
	for _, s := range r.Statements() {
		if s.DDL {
			out = append(out, Normalize(s.SQL, r.schema))
		}
	}
	return out
}

var (
	reSpace  = regexp.MustCompile(`\s+`)
	reXid    = regexp.MustCompile(`\s*/\* xid=\d+ \*/`)
	reServer = regexp.MustCompile(`\s*/\* generated by server \*/`)
	reUse    = regexp.MustCompile("^use `[^`]+`; ")
)

// Normalize puts a statement in the form of the golden files: whitespace collapsed, the
// qualifier of the schema, the "use" prefix and the comments of the server removed. The server
// rewrites some statements before it writes them (it drops the qualifier from DROP TABLE), so the
// comparison ignores what the server changes.
func Normalize(sql, schema string) string {
	sql = reUse.ReplaceAllString(strings.TrimSpace(sql), "")
	sql = reXid.ReplaceAllString(sql, "")
	sql = reServer.ReplaceAllString(sql, "")
	sql = strings.ReplaceAll(sql, "`"+schema+"`.", "")
	return strings.TrimSpace(reSpace.ReplaceAllString(sql, " "))
}

// run is one migration: a connection, and what is known about the tables.
type run struct {
	*Runner
	ctx  context.Context
	conn *sql.Conn
	opts Options

	shadow string
	pairs  []pair // shared columns, original to new
	keyOld string
	keyNew string
}

type pair struct{ old, new string }

func (r *Runner) begin(ctx context.Context, o Options) (*run, error) {
	conn, err := r.db.Conn(ctx)
	if err != nil {
		return nil, fmt.Errorf("connect: %w", err)
	}
	// The tools work in the schema of the table, and the server writes "use" before their DDL.
	if _, err := conn.ExecContext(ctx, "USE "+ident(r.schema)); err != nil {
		_ = conn.Close()
		return nil, fmt.Errorf("use %s: %w", r.schema, err)
	}
	if o.ChunkSize <= 0 {
		o.ChunkSize = 100
	}
	return &run{Runner: r, ctx: ctx, conn: conn, opts: o}, nil
}

func (m *run) end() { _ = m.conn.Close() }

func (m *run) q(name string) string { return "`" + m.schema + "`.`" + name + "`" }

func ident(name string) string { return "`" + strings.ReplaceAll(name, "`", "``") + "`" }

func (m *run) exec(ddl bool, query string, args ...any) error {
	m.mu.Lock()
	m.log = append(m.log, Statement{SQL: query, DDL: ddl})
	m.mu.Unlock()
	if _, err := m.conn.ExecContext(m.ctx, query, args...); err != nil {
		return fmt.Errorf("%s: %w", firstLine(query), err)
	}
	return nil
}

func firstLine(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	if len(s) > 120 {
		s = s[:120] + "..."
	}
	return s
}

func (m *run) exists(name string) (bool, error) {
	var n int
	err := m.conn.QueryRowContext(m.ctx, "SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ?", m.schema, name).Scan(&n)
	return n > 0, err
}

func (m *run) columns(name string) ([]string, error) {
	rows, err := m.conn.QueryContext(m.ctx, "SELECT COLUMN_NAME FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY ORDINAL_POSITION", m.schema, name)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	var out []string
	for rows.Next() {
		var c string
		if err := rows.Scan(&c); err != nil {
			return nil, err
		}
		out = append(out, c)
	}
	return out, rows.Err()
}

func (m *run) primaryKey(name string) (string, error) {
	rows, err := m.conn.QueryContext(m.ctx, "SELECT COLUMN_NAME FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? AND INDEX_NAME = 'PRIMARY'", m.schema, name)
	if err != nil {
		return "", err
	}
	defer func() { _ = rows.Close() }()
	var cols []string
	for rows.Next() {
		var c string
		if err := rows.Scan(&c); err != nil {
			return "", err
		}
		cols = append(cols, c)
	}
	if len(cols) != 1 {
		return "", fmt.Errorf("table %s needs a single-column primary key, it has %v", name, cols)
	}
	return cols[0], rows.Err()
}

var (
	reChange = regexp.MustCompile("(?i)\\bCHANGE\\s+(?:COLUMN\\s+)?`?(\\w+)`?\\s+`?(\\w+)`?")
	reRename = regexp.MustCompile("(?i)\\bRENAME\\s+COLUMN\\s+`?(\\w+)`?\\s+TO\\s+`?(\\w+)`?")
)

// renames reads the columns an ALTER renames, as the tools do to know which column of the new
// table takes its values from which column of the old one.
func renames(alter string) map[string]string {
	out := map[string]string{}
	for _, re := range []*regexp.Regexp{reChange, reRename} {
		for _, m := range re.FindAllStringSubmatch(alter, -1) {
			if m[1] != m[2] {
				out[m[1]] = m[2]
			}
		}
	}
	return out
}

// learn reads the structure of both tables once the shadow has its new structure: which columns
// are copied, and the key.
func (m *run) learn(alter string) error {
	oldCols, err := m.columns(m.table)
	if err != nil {
		return err
	}
	newCols, err := m.columns(m.shadow)
	if err != nil {
		return err
	}
	inNew := map[string]bool{}
	for _, c := range newCols {
		inNew[c] = true
	}
	ren := renames(alter)
	m.pairs = nil
	for _, c := range oldCols {
		target := c
		if to, ok := ren[c]; ok {
			target = to
		}
		if inNew[target] {
			m.pairs = append(m.pairs, pair{c, target})
		}
	}
	if m.keyOld, err = m.primaryKey(m.table); err != nil {
		return err
	}
	m.keyNew = m.keyOld
	if to, ok := ren[m.keyOld]; ok {
		m.keyNew = to
	}
	return nil
}

func (m *run) cols(newSide bool) string {
	var out []string
	for _, p := range m.pairs {
		if newSide {
			out = append(out, ident(p.new))
		} else {
			out = append(out, ident(p.old))
		}
	}
	return strings.Join(out, ", ")
}

// copyChunks copies the rows of the original table into the shadow in chunks of key values, with
// the statement insertSQL gives (two placeholders: the first key of the chunk, and the first key
// after it), and calls the hook after each.
func (m *run) copyChunks(insertSQL func() string, afterChunk func(chunk int) error) error {
	var lo, hi sql.NullInt64
	if err := m.conn.QueryRowContext(m.ctx, fmt.Sprintf("SELECT MIN(%s), MAX(%s) FROM %s", ident(m.keyOld), ident(m.keyOld), m.q(m.table))).Scan(&lo, &hi); err != nil {
		return fmt.Errorf("read the key range: %w", err)
	}
	if !lo.Valid {
		return nil
	}
	chunk := 0
	for from := lo.Int64; from <= hi.Int64; from += int64(m.opts.ChunkSize) {
		if err := m.exec(false, insertSQL(), from, from+int64(m.opts.ChunkSize)); err != nil {
			return err
		}
		chunk++
		if m.opts.ChunkPause > 0 {
			select {
			case <-time.After(m.opts.ChunkPause):
			case <-m.ctx.Done():
				return m.ctx.Err()
			}
		}
		if afterChunk != nil {
			if err := afterChunk(chunk); err != nil {
				return err
			}
		}
		if m.opts.DuringCopy != nil {
			m.opts.DuringCopy(chunk)
		}
	}
	return nil
}
